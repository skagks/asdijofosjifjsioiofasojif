"""Regenerate the UI images embedded in mhwmm/assets.py and the Windows icon.

Requires Pillow:  python tools/make_assets.py
"""

from __future__ import annotations

import base64
import io
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SS = 8  # supersampling factor for anti-aliasing

ACCENT = (230, 167, 75, 255)
ACCENT_DARK = (204, 143, 54, 255)
INK = (29, 20, 8, 255)
OUTLINE = (124, 129, 140, 255)
TRACK_OFF = (112, 117, 128, 255)
KNOB = (250, 248, 244, 255)
TILE = (26, 29, 35, 255)
TILE_EDGE = (58, 51, 38, 255)


def _finish(img: Image.Image, size: tuple[int, int]) -> Image.Image:
    return img.resize(size, Image.LANCZOS)


def checkbox(size: int, on: bool) -> Image.Image:
    s = size * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad = s * 0.08
    radius = s * 0.24
    box = (pad, pad, s - pad, s - pad)
    if on:
        d.rounded_rectangle(box, radius=radius, fill=ACCENT)
        w = max(1, round(s * 0.13))
        pts = [(s * 0.28, s * 0.52), (s * 0.44, s * 0.68), (s * 0.73, s * 0.35)]
        d.line(pts, fill=INK, width=w, joint="curve")
        for x, y in (pts[0], pts[-1]):
            d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=INK)
    else:
        d.rounded_rectangle(box, radius=radius, outline=OUTLINE, width=max(1, round(s * 0.085)))
    return _finish(img, (size, size))


def switch(height: int, on: bool) -> Image.Image:
    width = round(height * 1.8)
    w, h = width * SS, height * SS
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad = h * 0.06
    d.rounded_rectangle((pad, pad, w - pad, h - pad), radius=(h - 2 * pad) / 2, fill=ACCENT if on else TRACK_OFF)
    r = h * 0.34
    cx = w - h / 2 if on else h / 2
    cy = h / 2
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=KNOB)
    return _finish(img, (width, height))


def _claw(d: ImageDraw.ImageDraw, p0, p1, p2, width: float, color) -> None:
    """A tapered slash along a quadratic curve."""
    n = 64
    left, right = [], []
    for i in range(n + 1):
        t = i / n
        x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0]
        y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]
        dx = 2 * (1 - t) * (p1[0] - p0[0]) + 2 * t * (p2[0] - p1[0])
        dy = 2 * (1 - t) * (p1[1] - p0[1]) + 2 * t * (p2[1] - p1[1])
        length = math.hypot(dx, dy) or 1
        nx, ny = -dy / length, dx / length
        half = width / 2 * math.sin(math.pi * t) ** 0.75
        left.append((x + nx * half, y + ny * half))
        right.append((x - nx * half, y - ny * half))
    d.polygon(left + right[::-1], fill=color)


def app_icon(size: int) -> Image.Image:
    s = size * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    pad = s * 0.04
    d.rounded_rectangle((pad, pad, s - pad, s - pad), radius=s * 0.22, fill=TILE,
                        outline=TILE_EDGE, width=max(1, round(s * 0.03)))
    for i, color in enumerate((ACCENT_DARK, ACCENT, ACCENT_DARK)):
        off = (i - 1) * s * 0.17
        _claw(d, (s * 0.70 + off, s * 0.18), (s * 0.46 + off, s * 0.44), (s * 0.30 + off, s * 0.82), s * 0.12, color)
    return _finish(img, (size, size))


def b64png(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main() -> None:
    images: dict[str, dict[int, str]] = {
        "check_on": {n: b64png(checkbox(n, True)) for n in (16, 20, 24, 28, 32)},
        "check_off": {n: b64png(checkbox(n, False)) for n in (16, 20, 24, 28, 32)},
        "switch_on": {n: b64png(switch(n, True)) for n in (16, 20, 24, 28)},
        "switch_off": {n: b64png(switch(n, False)) for n in (16, 20, 24, 28)},
        "logo": {n: b64png(app_icon(n)) for n in (28, 32, 40, 48, 64)},
    }
    lines = [
        '"""UI images (generated by tools/make_assets.py, do not edit)."""',
        "",
        "# name -> {nominal pixel size: base64 PNG}",
        "IMAGES = {",
    ]
    for name, sizes in images.items():
        lines.append(f"    {name!r}: {{")
        for n, data in sizes.items():
            lines.append(f"        {n}: (")
            for i in range(0, len(data), 96):
                lines.append(f"            {data[i:i + 96]!r}")
            lines.append("        ),")
        lines.append("    },")
    lines.append("}")
    (ROOT / "mhwmm" / "assets.py").write_text("\n".join(lines) + "\n", encoding="utf-8")

    icon_dir = ROOT / "assets"
    icon_dir.mkdir(exist_ok=True)
    big = app_icon(256)
    big.save(icon_dir / "icon.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    big.save(icon_dir / "icon.png")
    print("assets written")


if __name__ == "__main__":
    main()
